def swap(s):
    out = []
    oc = True
    for ch in s:
        if ch == '"':
            out.append("\u201c" if oc else "\u201d")
            oc = not oc
        elif ch in "\u201c\u201d":
            out.append('"')
        else:
            out.append(ch)
    return "".join(out)


def rep(t, old, new, label):
    if old in t:
        return t.replace(old, new, 1), True
    alt = swap(old)
    if alt in t:
        return t.replace(alt, swap(new), 1), True
    print(f"[MISS] {label}")
    return t, False


